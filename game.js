  function drawAmbient() {
    const canvas = $('#ambient');
    if (!canvas) return;
    const ctx = canvas.getContext('2d');
    let w = 0, h = 0;
    const dpr = Math.min(2, window.devicePixelRatio || 1);

    function resize() {
      w = window.innerWidth;
      h = window.innerHeight;
      canvas.width = Math.floor(w * dpr);
      canvas.height = Math.floor(h * dpr);
      ctx.setTransform(dpr, 0, 0, dpr, 0, 0);
    }
    resize();
    window.addEventListener('resize', resize);

    const reduced = window.matchMedia('(prefers-reduced-motion: reduce)').matches;
    const count = w < 700 ? 26 : 52;
    const colors = [38, 325, 265, 160];
    const parts = Array.from({ length: count }, () => ({
      x: Math.random() * w,
      y: Math.random() * h,
      r: Math.random() * 1.8 + 0.5,
      s: Math.random() * 0.35 + 0.08,
      o: Math.random() * 0.45 + 0.12,
      hue: pick(colors)
    }));

    if (reduced) {
      ctx.clearRect(0, 0, w, h);
      parts.forEach((p) => {
        ctx.beginPath();
        ctx.fillStyle = `hsla(${p.hue},90%,72%,${p.o})`;
        ctx.arc(p.x, p.y, p.r, 0, Math.PI * 2);
        ctx.fill();
      });
      return;
    }

    let last = performance.now();
    function frame(now) {
      if (document.body.classList.contains('perf')) {
        last = now;
        requestAnimationFrame(frame);
        return;
      }
      const dt = Math.min(48, now - last);
      last = now;
      ctx.clearRect(0, 0, w, h);
      ctx.globalCompositeOperation = 'lighter';
      for (const p of parts) {
        p.y -= p.s * dt * 0.055;
        p.x += Math.sin(now / 3200 + p.y * 0.01) * 0.1;
        if (p.y < -12) { p.y = h + 12; p.x = Math.random() * w; }
        if (p.x < -12) p.x = w + 12;
        if (p.x > w + 12) p.x = -12;
        ctx.beginPath();
        ctx.fillStyle = `hsla(${p.hue},90%,72%,${p.o})`;
        ctx.shadowColor = `hsla(${p.hue},90%,70%,0.8)`;
        ctx.shadowBlur = 10;
        ctx.arc(p.x, p.y, p.r, 0, Math.PI * 2);
        ctx.fill();
      }
      ctx.globalCompositeOperation = 'source-over';
      requestAnimationFrame(frame);
    }
    requestAnimationFrame(frame);
  }

