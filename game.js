  function useItem(id) {
    if (!S || !S.items[id] || !ITEMS[id]) return;
    if (combat && combat.over) return;
    if (combat && combat.locked) return;
    const it = ITEMS[id];
    S.items[id] -= 1;
    if (S.items[id] <= 0) delete S.items[id];
    S.itemsUsed += 1;

    if (it.heal > 0) S.hp = Math.min(S.maxHp, S.hp + it.heal);
    if (it.heal < 0) S.hp = Math.max(1, S.hp + it.heal);
    if (it.mp) S.mp = Math.min(S.maxMp, S.mp + it.mp);

    sfx('heal');
    toast(it.emoji, `${it.name}: использовано`);
    syncHUD(); save();
    renderBag();

    if (combat && !combat.over) {
      combat.locked = true;
      $('#modal-bag').hidden = true;
      addLog(`🎒 Ты используешь «${it.name}».`, 'player');
      if (it.heal > 0) { popDamage(it.heal, 'heal'); addLog(`❤️ +${it.heal} HP.`, 'good'); }
      if (it.heal < 0) { popDamage(-it.heal, ''); addLog(`💔 ${it.heal} HP.`, 'bad'); }
      if (it.mp > 0) addLog(`🔮 +${it.mp} MP.`, 'good');
      if (S.cls === 'rogue') { combat.stamps = 0; addLog('📦 Заказ сброшен: клиент ждёт.', 'sys'); }
      renderCombat();
      (async () => {
        await sleep(320);
        await afterPlayerAction();
        if (combat && !combat.over) { combat.locked = false; renderCombat(); }
      })();
    }
  }

