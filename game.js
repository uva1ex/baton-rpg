  function runTiming(label) {
    return new Promise((resolve) => {
      if (window.BATON && window.BATON.autoTiming) {
        setTimeout(() => resolve(1), 40);
        return;
      }
      const box = $('#timing');
      const track = $('#timing-track');
      const cursor = $('#timing-cursor');
      $('#timing-label').textContent = label;
      box.hidden = false;
      timingActive = true;

      let settled = false;
      let pos = 0;
      const start = performance.now();
      const period = 1500;

      function frame(now) {
        if (settled) return;
        const phase = (now - start) % period;
        const half = period / 2;
        pos = phase < half ? (phase / half) * 100 : (1 - (phase - half) / half) * 100;
        cursor.style.left = pos + '%';
        requestAnimationFrame(frame);
      }
      requestAnimationFrame(frame);

      function computeQuality() {
        const d = Math.abs(pos - 50);
        if (d <= 8) return 1.7;
        if (d <= 26) return 1;
        return 0.62;
      }

      function settle(q) {
        if (settled) return;
        settled = true;
        timingActive = false;
        box.hidden = true;
        document.removeEventListener('keydown', onKey);
        track.removeEventListener('pointerdown', onClick);
        resolve(q);
      }

      function onClick(e) {
        e.preventDefault();
        settle(computeQuality());
      }
      function onKey(e) {
        if (e.code === 'Space' || e.code === 'Enter') {
          e.preventDefault();
          settle(computeQuality());
        }
      }

      track.addEventListener('pointerdown', onClick);
      document.addEventListener('keydown', onKey);
      setTimeout(() => settle(0.85), 2700);
    });
  }

