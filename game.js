      if (S.gear.includes(id)) {
        toast(it.emoji, `${it.name} уже надет. Второй не нужен.`);
        return;
      }
      S.gear.push(id);
      Object.entries(it.equip).forEach(([stat, val]) => {
        if (stat === 'atk') S.atk += val;
        else if (stat === 'mag') S.mag += val;
        else if (stat === 'luck') S.luck += val;
        else if (stat === 'hp') { S.maxHp += val; S.hp += val; }
      });
      toast(it.emoji, `${it.name} — надето!`);
      syncHUD(); save();
      return;
