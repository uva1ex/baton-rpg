  async function doSkill(id) {
    const sk = SKILLS[id];
    if (!sk || S.mp < sk.cost) return;
    S.mp -= sk.cost;
    addLog(`✨ <b>${sk.name}</b>`, 'player');
    let q = 1;
    if (sk.dmg) q = await runTiming(sk.name);
    if (!combat || combat.over) return;

    if (sk.heal) {
      const h = Math.round(S.maxHp * sk.heal);
      S.hp = Math.min(S.maxHp, S.hp + h);
      popDamage(h, 'heal');
      addLog(`❤️ Ты восстанавливаешь <span class="num">${h}</span> HP.`, 'good');
      sfx('heal');
    }
    if (sk.dmg) {
      const { dmg, crit } = heroDamage(sk.dmg, sk.mult, q);
      addLog(`Урон: <span class="num">${dmg}</span>${crit ? ' <span class="crit">КРИТ!</span>' : ''}`, 'player');
      hitFoe(dmg, crit);
    }
    if (sk.self) {
      S.hp = Math.max(1, S.hp - sk.self);
      addLog(`😭 Ты плачешь. −${sk.self} HP.`, 'bad');
    }
    if (sk.burn) {
      combat.burn = 2;
      combat.burnDmg = Math.max(3, Math.round(S.mag * 0.4));
      addLog('🔥 Враг горит. Будет больно ещё два хода.', 'good');
    }
    if (sk.stun) {
      if (combat.foe.boss && chance(0.5)) addLog('Менеджер отзывает заказ. Стан не сработал.', 'bad');
      else { combat.stun = Math.max(combat.stun, sk.stun); addLog('💫 Враг теряет ход.', 'good'); }
    }
    if (sk.stunChance) {
      if (combat.foe.boss && chance(0.6)) addLog('Менеджер не смеётся. У него нет души.', 'bad');
      else if (chance(sk.stunChance)) { combat.stun = Math.max(combat.stun, 1); addLog('💫 Враг засмеялся и пропустит ход.', 'good'); }
      else addLog('Враг не понял мем. Но сделал вид.', 'foe');
    }
    if (sk.buff) {
      combat.buff = Math.max(combat.buff, sk.buff);
      addLog('📈 Ты в ударе: +30% к урону на 3 хода.', 'good');
    }
    if (sk.dmg) combat.lastSkillName = sk.name;
    if (S.cls === 'mage') {
      combat.tabs = Math.min(4, (combat.tabs || 0) + 1);
      if (combat.tabs === 4) addLog('🗂️ Четыре вкладки. Браузер тормозит: урон −20%, пока не закроешь вкладки.', 'sys');
    }
    if (S.cls === 'bard') addFollowers(10);
    if (sk.dmg && combat.hp > 0) addStamp();
    renderCombat();
    await sleep(480);
    await afterPlayerAction();
  }

  async function doMeme() {
    const foe = combat.foe;
    combat.memeCd = 3;
    S.memes += 1;
    const baseList = MEMES.concat(CLASS_MEMES[S.cls] || []);
    let pool = baseList.map((m) => ({
      ...m,
      w: m.w * (foe.boss && m.id === 'stun' ? 0.35 : 1) * (foe.boss && m.id === 'cringe' ? 2.5 : 1)
    }));
    const total = pool.reduce((a, m) => a + m.w, 0);
    let r = Math.random() * total;
    let chosen = pool[0];
    for (const m of pool) { r -= m.w; if (r <= 0) { chosen = m; break; } }
    addLog(`😹 <b>${chosen.text}</b>`, 'player');
    if (foe.boss && chosen.id === 'cringe') addLog('— Я видел этот мем в презентации 2019 года. — Менеджер даже не улыбнулся.', 'foe');
    const res = chosen.do();
    if (res) addLog(res, 'sys');
    if (S.cls === 'bard') addFollowers(chosen.id === 'cringe' ? -20 : 15);
    S.likes = (S.likes || 0) + 3;
    if (combat.foeId === 'algorithm') {
      combat.reach = Math.max(0, (combat.reach || 0) - 4);
      addLog('📉 Мем сбивает охваты: −4.', 'good');
    }
    sfx('meme');
    renderCombat();
    await sleep(620);
    await afterPlayerAction();
  }

