  function chooseMove() {
    const foe = combat.foe;
    const list = (combat.phase === 2 && foe.moves2) ? foe.moves2 : foe.moves;
    let pool = list.filter((m) => m.name !== combat.lastMove);
    if (!pool.length) pool = list;
    const total = pool.reduce((a, m) => a + (m.w || 1), 0);
    let r = Math.random() * total;
    for (const m of pool) {
      r -= m.w || 1;
      if (r <= 0) { combat.lastMove = m.name; return m; }
    }
    combat.lastMove = pool[0].name;
    return pool[0];
  }

  async function enemyTurn() {
    if (!combat || combat.over) return;
    const foe = combat.foe;
    if (combat.stun > 0) {
      combat.stun -= 1;
      addLog(`💫 <b>${esc(foe.name)}</b> пропускает ход. Ему нехорошо.`, 'good');
      renderCombat();
      await sleep(380);
      return;
    }
    if (!foe.boss && CLASS_TAUNTS[S.cls] && combat.turn - (combat.lastClassTaunt || 0) >= 3 && chance(0.35)) {
      addLog(esc(pick(CLASS_TAUNTS[S.cls])), 'foe');
      combat.lastClassTaunt = combat.turn;
      await sleep(280);
    }
    const move = chooseMove();
    addLog(`<b>${esc(foe.name)}</b> использует «${move.name}».`, 'foe');
    await sleep(340);
    if (move.text) addLog(move.text, 'foe');
    if (foe.name === 'Батон-Двойник' && move.name === 'Повторить за тобой' && combat.lastSkillName) {
      addLog(`Двойник повторяет «${combat.lastSkillName}». Копия хуже оригинала.`, 'foe');
    }

    if (move.heal) {
      const h = Math.round(combat.maxHp * move.heal);
      combat.hp = Math.min(combat.maxHp, combat.hp + h);
      addLog(`💚 Враг восстанавливает <span class="num">${h}</span> HP.`, 'bad');
      popDamage(h, 'heal');
    }
    if (move.buff) {
      combat.atk *= 1 + move.buff;
      combat.weaken = 0;
      addLog('⬆️ Враг становится увереннее в себе. К сожалению.', 'bad');
    }
    if (move.power > 0) {
      const dodgeChance = Math.min(0.22, 0.02 + S.luck * 0.007);
      if (chance(dodgeChance)) {
        addLog('🌬 Ты уклоняешься. Красиво. Случайно.', 'good');
        popDamage('мимо', 'miss');
      } else {
        let dmg = combat.atk * move.power * rnd(0.9, 1.1);
        if (combat.weaken > 0) dmg *= 0.75;
        dmg *= 1 - S.def / (S.def + 55);
        if (combat.guard) dmg *= 0.4;
        if (foe.name === 'Алгоритм' && combat.reach >= 10 && move.power > 0) {
          dmg *= 1.6;
          combat.reach = 0;
          addLog('📈 Алгоритм выводит тебя в тренды. Это больно.', 'bad');
        }
        dmg = Math.max(1, Math.round(dmg));
        S.hp -= dmg;
        if (S.cls === 'warrior') {
          combat.rage = Math.min(100, (combat.rage || 0) + dmg);
          if (combat.rage >= 100) addLog('😤 Ты на грани. Ещё немного — и накипит.', 'sys');
        }
        if (combat.guard) addLog('🛡️ Блок поглотил большую часть удара.', 'good');
        addLog(`Ты получаешь <span class="num">${dmg}</span> урона.`, 'bad');
        popDamage(dmg, '');
        const arena = $('#arena');
        arena.classList.remove('shake');
        void arena.offsetWidth;
        arena.classList.add('shake');
        sfx('hurt');
      }
    }
    if (move.drain) {
      const m = Math.min(S.mp, move.drain);
      S.mp -= m;
      addLog(`🔮 Враг высасывает <span class="num">${m}</span> маны.`, 'bad');
    }
    if (move.poison) {
      combat.ppoison = move.poison;
      combat.ppoisonDmg = 4 + Math.floor(S.level * 0.8);
      addLog('🧪 Ты отравлен унынием. Неприятно, но жить можно.', 'bad');
    }
    if (foe.name === 'Алгоритм') {
      combat.reach = Math.min(10, (combat.reach || 0) + 2);
      if ([2, 4, 6, 8, 10].includes(combat.reach)) addLog(`📈 Охваты: ${combat.reach}/10.`, 'sys');
    }
    if (combat.weaken > 0) combat.weaken -= 1;
    renderCombat();
    syncHUD();
    await sleep(420);
    if (S.hp <= 0) onDefeat();
  }

  async function afterPlayerAction() {
    if (!combat || combat.over) return;
    if (combat.hp <= 0) { onVictory(); return; }

    if (combat.burn > 0) {
      combat.burn -= 1;
      combat.hp -= combat.burnDmg;
      addLog(`🔥 Враг горит: <span class="num">${combat.burnDmg}</span> урона.`, 'good');
      popDamage(combat.burnDmg, '');
      renderCombat();
      if (combat.hp <= 0) { onVictory(); return; }
    }

    await sleep(300);
    if (!combat || combat.over) return;
    await enemyTurn();
    if (!combat || combat.over) return;

    if (combat.ppoison > 0) {
      combat.ppoison -= 1;
      S.hp -= combat.ppoisonDmg;
      addLog(`🧪 Яд уныния: <span class="num">${combat.ppoisonDmg}</span> урона тебе.`, 'bad');
      popDamage(combat.ppoisonDmg, '');
      syncHUD();
      if (S.hp <= 0) { onDefeat(); return; }
    }

    combat.memeCd = Math.max(0, combat.memeCd - 1);
    combat.gooseCd = Math.max(0, (combat.gooseCd || 0) - 1);
    combat.buff = Math.max(0, combat.buff - 1);
    combat.guard = false;
    combat.turn += 1;
    combat.locked = false;
    renderCombat();
  }

