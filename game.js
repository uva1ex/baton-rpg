    let pts = 0;
    if (S.deaths === 0) pts += 2; else if (S.deaths <= 1) pts += 1;
    if (S.memes >= 4) pts += 1;
    if (S.turns <= 55) pts += 1;
    if (pts >= 3 && S.deaths === 0) return { letter: 'S', title: 'Идеальный сотрудник', text: 'Тебе даже готовы доверить настоящий проект. Шучу. Но ты справился.' };
    if (pts >= 2) return { letter: 'A', title: 'Ценный кадр', text: 'Отличная работа. В резюме появилась строчка «спас королевство». Неплохо для вторника.' };
    if (pts === 1) return { letter: 'B', title: 'Стабильный результат', text: 'Ты справился. Не идеально, но батон не жалуется. Он вообще молчаливый.' };
    return { letter: 'C', title: 'Батон вернулся, и ладно', text: 'Репутация — не совсем. Но шаурма всё компенсирует. Наверное.' };
