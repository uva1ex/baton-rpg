    if (item.once) S.shop[id] = true;
    item.apply();
    syncHUD(); save(); renderShop();
    const sb = $('#btn-shop');
    if (sb) sb.textContent = `🥟 Шаурмичная · ${S.likes || 0} ❤️`;
    if (item.once) toast(item.emoji, `${item.name} — куплено. Бабушка довольна.`);
